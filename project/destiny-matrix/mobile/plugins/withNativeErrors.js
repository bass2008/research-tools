const { withAndroidManifest, withMainApplication, AndroidConfig } = require('expo/config-plugins');
const fs = require('node:fs/promises');
const path = require('node:path');

const START = '// @generated begin arcana-native-errors';
const END = '// @generated end arcana-native-errors';

function patchMainApplication(source, language) {
  if (!['kt', 'java'].includes(language)) throw new Error('Native errors require a Kotlin or Java MainApplication');
  // Repeated prebuilds replace the generated block, including a changed DSN.
  const clean = source.replace(/\n[ \t]*\/\/ @generated begin arcana-native-errors[\s\S]*?\/\/ @generated end arcana-native-errors\n?/g, '\n');
  if (clean.includes('RNSentrySDK.init(')) throw new Error('Remove useNativeInit from the Sentry plugin: Arcana owns the privacy-filtered native initialization');
  const anchor = /^([ \t]*)super\.onCreate\(\);?[ \t]*$/m;
  if (!anchor.test(clean)) throw new Error('Cannot safely locate MainApplication.onCreate for native error initialization');
  return clean.replace(anchor, (line, indent) => `${line}\n${indent}${START}\n${indent}ArcanaNativeErrors.init(this)${language === 'java' ? ';' : ''}\n${indent}${END}`);
}

function nativeSource(packageName, { dsn = '', release = 'mobile@0.1.0', local = false } = {}) {
  if (!/^[A-Za-z_]\w*(\.[A-Za-z_]\w*)+$/.test(packageName)) throw new Error('Invalid Android package');
  return `// Generated by withNativeErrors.js. Change the plugin, never this file.
package ${packageName};

import android.content.Context;
import io.sentry.Hint;
import io.sentry.SentryEvent;
import io.sentry.android.core.SentryAndroidOptions;
import io.sentry.protocol.Device;
import io.sentry.protocol.Mechanism;
import io.sentry.protocol.OperatingSystem;
import io.sentry.protocol.SdkVersion;
import io.sentry.protocol.SentryException;
import io.sentry.protocol.SentryStackFrame;
import io.sentry.protocol.SentryStackTrace;
import io.sentry.react.RNSentrySDK;
import java.util.ArrayList;
import java.util.List;

public final class ArcanaNativeErrors {
  private static final String DSN = ${JSON.stringify(String(dsn))};
  private static final String RELEASE = ${JSON.stringify(String(release))};
  private static final String ENVIRONMENT = ${JSON.stringify(local ? 'local' : 'production')};
  private ArcanaNativeErrors() {}

  public static void init(Context context) {
    if (DSN.isEmpty()) return;
    RNSentrySDK.init(context, options -> {
      configure(options);
      options.setBeforeSend((event, hint) -> sanitize(event, hint));
    });
  }

  static void configure(SentryAndroidOptions options) {
    options.setDsn(DSN);
    options.setRelease(RELEASE);
    options.setEnvironment(ENVIRONMENT);
    options.setDebug(false);
    options.setSendDefaultPii(false);
    options.setAttachServerName(false);
    options.setSendClientReports(false);
    options.setSendModules(false);
    options.setEnableAutoSessionTracking(false);
    options.setEnableScreenTracking(false);
    options.setMaxBreadcrumbs(0);
    options.setBeforeBreadcrumb((breadcrumb, hint) -> null);
    options.setEnableActivityLifecycleBreadcrumbs(false);
    options.setEnableAppLifecycleBreadcrumbs(false);
    options.setEnableSystemEventBreadcrumbs(false);
    options.setEnableSystemEventBreadcrumbsExtras(false);
    options.setEnableAppComponentBreadcrumbs(false);
    options.setEnableNetworkEventBreadcrumbs(false);
    options.setEnableUserInteractionBreadcrumbs(false);
    options.setEnableUserInteractionTracing(false);
    options.setEnableAutoActivityLifecycleTracing(false);
    options.setEnableStandaloneAppStartTracing(false);
    options.setEnableAutoTraceIdGeneration(false);
    options.setEnableFramesTracking(false);
    options.setTracesSampleRate(0.0);
    options.setTracesSampler(null);
    options.setProfilesSampleRate(0.0);
    options.setProfileSessionSampleRate(0.0);
    options.setProfilesSampler(null);
    options.setStartProfilerOnAppStart(false);
    options.setEnableAppStartProfiling(false);
    options.setAnrProfilingSampleRate(0.0);
    options.setTracePropagationTargets(new ArrayList<>());
    options.setAttachScreenshot(false);
    options.setAttachViewHierarchy(false);
    options.setAttachAnrThreadDump(false);
    options.setAttachThreads(false);
    options.setAttachStacktrace(true);
    options.setCollectAdditionalContext(false);
    options.setCollectExternalStorageContext(false);
    options.setEnableRootCheck(false);
    options.setSessionReplay(new io.sentry.SentryReplayOptions(false, options.getSdkVersion()));
    options.getSessionReplay().setSessionSampleRate(0.0);
    options.getSessionReplay().setOnErrorSampleRate(0.0);
    options.getLogs().setEnabled(false);
    options.getMetrics().setEnabled(false);
    options.setEnableSpotlight(false);
    // Raw NDK minidumps bypass Java beforeSend and may contain arbitrary memory.
    // Keep Java/Kotlin crashes and ANRs, with a whitelist applied before sending.
    options.setEnableNdk(false);
    options.setEnableScopeSync(false);
    options.setEnableNdkAppHangTracking(false);
    options.setTombstoneEnabled(false);
    options.setReportHistoricalTombstones(false);
    options.setAttachRawTombstone(false);
    options.setBeforeSendTransaction((transaction, hint) -> null);
    options.setBeforeSendReplay((replay, hint) -> null);
  }

  static SentryEvent sanitize(SentryEvent original, Hint hint) {
    // Construct a fresh object: future SDK fields cannot silently add account data.
    hint.clearAttachments();
    hint.setScreenshot(null);
    hint.setViewHierarchy(null);
    hint.setThreadDump(null);
    hint.setTombstone(null);
    hint.setReplayRecording(null);
    SentryEvent clean = new SentryEvent(original.getTimestamp());
    clean.setEventId(original.getEventId());
    clean.setLevel(original.getLevel());
    clean.setRelease(RELEASE);
    clean.setEnvironment(ENVIRONMENT);
    clean.setPlatform("java");
    if (original.getSdk() != null) {
      clean.setSdk(new SdkVersion(original.getSdk().getName(), original.getSdk().getVersion()));
    }
    OperatingSystem originalOs = original.getContexts().getOperatingSystem();
    if (originalOs != null) {
      OperatingSystem os = new OperatingSystem();
      os.setName("Android");
      os.setVersion(originalOs.getVersion());
      clean.getContexts().setOperatingSystem(os);
    }
    Device originalDevice = original.getContexts().getDevice();
    if (originalDevice != null) {
      Device device = new Device();
      device.setModel(originalDevice.getModel());
      clean.getContexts().setDevice(device);
    }
    List<SentryException> exceptions = new ArrayList<>();
    if (original.getExceptions() != null) {
      for (SentryException source : original.getExceptions()) {
        SentryException exception = new SentryException();
        exception.setType(symbol(source.getType()));
        exception.setModule(symbol(source.getModule()));
        exception.setValue("Native crash");
        if (source.getMechanism() != null) {
          Mechanism mechanism = new Mechanism();
          mechanism.setType("generic");
          mechanism.setHandled(source.getMechanism().isHandled());
          exception.setMechanism(mechanism);
        }
        if (source.getStacktrace() != null && source.getStacktrace().getFrames() != null) {
          List<SentryStackFrame> frames = new ArrayList<>();
          for (SentryStackFrame sourceFrame : source.getStacktrace().getFrames()) {
            SentryStackFrame frame = new SentryStackFrame();
            frame.setFunction(symbol(sourceFrame.getFunction()));
            frame.setModule(symbol(sourceFrame.getModule()));
            String filename = sourceFrame.getFilename();
            if (filename != null && filename.matches("[A-Za-z0-9_.$-]+\\\\.(java|kt|kts)")) frame.setFilename(filename);
            frame.setLineno(sourceFrame.getLineno());
            frame.setColno(sourceFrame.getColno());
            frame.setInApp(sourceFrame.isInApp());
            frames.add(frame);
          }
          exception.setStacktrace(new SentryStackTrace(frames));
        }
        exceptions.add(exception);
      }
    }
    clean.setExceptions(exceptions);
    return clean;
  }

  private static String symbol(String value) {
    return value != null && value.length() <= 250 && value.matches("[A-Za-z_$<>][A-Za-z0-9_.$<>-]*") ? value : null;
  }
}
`;
}

function withNativeErrors(config, options = {}) {
  config = withAndroidManifest(config, mod => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(mod.modResults);
    const metadata = app['meta-data'] ?? [];
    app['meta-data'] = [...metadata.filter(item => item.$['android:name'] !== 'io.sentry.auto-init'),
      { $: { 'android:name': 'io.sentry.auto-init', 'android:value': 'false' } }];
    return mod;
  });
  return withMainApplication(config, async mod => {
    const main = mod.modResults;
    const packageName = /^package\s+([\w.]+);?$/m.exec(main.contents)?.[1];
    if (!packageName || !main.path) throw new Error('Cannot locate Android package for native error filtering');
    main.contents = patchMainApplication(main.contents, main.language);
    await fs.writeFile(path.join(path.dirname(main.path), 'ArcanaNativeErrors.java'), nativeSource(packageName, options), 'utf8');
    return mod;
  });
}

module.exports = withNativeErrors;
module.exports.patchMainApplication = patchMainApplication;
module.exports.nativeSource = nativeSource;
