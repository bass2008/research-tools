  resources: (a) => `Канал ресурса открывает одно: ${a.gift}. Перекрывает его ${a.shadow}.`,
  family_gifts: (a) => `Род передал главное: ${a.gift}. Цена дара — ${a.shadow}.`,
  soul_tasks: (a) => `Внутренняя работа: ${a.advice}. Больше всего мешает ${a.shadow}.`,
  past_lives: (a) => `С прошлого витка пришло своё: ${a.gift}, и вместе с ним ${a.shadow}. Сюжет заканчивается, когда получается ${a.advice}.`,
  purpose: (a) => `Предназначение читается так: ${a.essence}.`,
  money: (a) => `Деньги приносит именно это: ${a.gift}. Уводит их ${a.shadow}.`,
  money40: (a) => `После сорока доход держится не на скорости: человек ${a.verb} увереннее, чем раньше. Риск прежний — ${a.shadow}.`,
  relations: (a) => `В паре аркан даёт своё: ${a.gift}. Трудность — ${a.shadow}.`,
  parents_children: (a) => `С родителями и детьми повторяется ${a.shadow}. Опора — ${a.gift}.`,
  ancestry: (a) => `Родовая тема — ${a.essence}. Ваша роль: ${a.advice}.`,
  body_resource: (a) => `Силы возвращает свой темп: ${a.short}. Теряются они на другом — ${a.shadow}.`,
  chakras: (a) => `На своём уровне карты аркан даёт это: ${a.gift}. При перекосе — ${a.shadow}.`,
  rest: (a) => `Отдых по этому аркану — ${a.short}, а не общий список активностей.`,
  loops: (a) => `Программа крутится вокруг одного — ${a.shadow}. Выход: ${a.advice}.`,
  years: (a) => `Десятилетие под этим арканом идёт про одно: ${a.essence}.`,

  day: (a) => `Визитка: ${a.gift}. Это видно в первые минуты знакомства, ещё до слов.`,
  month: (a) => `Дано от рождения: ${a.gift}. Работает без разгона, поэтому редко считается своей сильной стороной.`,
  year: (a) => `Опора рода — ${a.essence}. Это условия, в которых разворачивался характер.`,
  mission: (a) => `Разворачивает туда, где нужно ${a.advice}.`,
  center: (a) => `В центре карты аркан задаёт состояние, из которого человек ${a.verb}. Само состояние — ${a.essence}.`,
  father_line: (a) => `По отцовской линии пришло своё: ${a.gift}, а вместе с ним ${a.shadow}.`,
  mother_line: (a) => `По материнской линии пришло своё: ${a.gift}. Изнанка дара — ${a.shadow}.`,
  descendants: (a) => `Дальше по роду уходит одно: ${a.gift}. Передаётся и ${a.shadow}.`,
  inheritance: (a) => `Незакрытая задача рода — ${a.shadow}. Закрывается она так: ${a.advice}.`,
  comfort_west: (a) => `Равновесие приходит через себя: ${a.advice}.`,
  comfort_north: (a) => `В близости восстанавливает своё: ${a.gift}. Изматывает ${a.shadow}.`,
  comfort_east: (a) => `Устойчивость в быту и деньгах даёт это: ${a.gift}.`,
  comfort_south: (a) => `Работа не выжигает, пока человек ${a.verb} в своём темпе. Выжигает ${a.shadow}.`,
