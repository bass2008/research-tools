// Толкование «аркан в позиции», собранное из формулы позиции и сути аркана. Отдельным
// модулем намеренно: его читает и энциклопедия, и сборка разделов, а держать его в
// encyclopedia.ts значило замкнуть кольцо sections → content → encyclopedia → sections.
