/** Встроенный текст «аркан n в позиции key». Сгенерированный корпус подмешивает `lib/content`. */
export function builtInPositionText(n: number, key: string): string {
  const a = arcanum(n);
  const frame = POSITION_FRAME[key];
  if (!frame) return `В этой позиции аркан читается как ${a.essence}.`;
  return Array.isArray(frame) ? frame[(n - 1) % frame.length](a) : frame(a);
}
