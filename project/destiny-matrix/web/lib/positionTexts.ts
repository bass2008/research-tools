  character: (a) => `В характере это ${a.short}. Сильная сторона — ${a.gift}. Перекос — ${a.shadow}.`,
  comfort: (a) => `Восстанавливает своё: ${a.short}. Выбивает из равновесия другое — ${a.shadow}.`,
