export interface CombinationPage {
  a: number;
  b: number;
  slug: string;
  title: string;
  short: string;
  paragraphs: string[];
}

export function combinationHref(a: number, b: number): string {
  const [lo, hi] = a <= b ? [a, b] : [b, a];
  return `/encyclopedia/combination/${lo}-${hi}`;
}

export function allCombinationSlugs(): string[] {
  const out: string[] = [];
  for (let a = 1; a <= 22; a++) for (let b = a + 1; b <= 22; b++) out.push(`${a}-${b}`);
  return out;
}

export function parseCombinationSlug(slug: string): [number, number] | null {
  const m = /^(\d{1,2})-(\d{1,2})$/.exec(slug);
  if (!m) return null;
  const a = Number(m[1]);
  const b = Number(m[2]);
  if (!(a >= 1 && a < b && b <= 22)) return null;
  return [a, b];
}

