/* ── аркан целиком, по контракту ArcanumEntry ── */

export function arcanumEntry(n: number): ArcanumEntry {
  const a = arcanum(n);
  const combinations: CombinationRef[] = [];
  for (let other = 1; other <= 22; other++) {
    if (other === n) continue;
    const o = arcanum(other);
    combinations.push({
      with: other,
      href: combinationHref(n, other),
      short: pairShort(a, o),
    });
  }
  const handwritten = a.inPositions as unknown as Record<string, string | undefined>;
  const inPositions: Record<string, string> = {};
  for (const s of CATALOG) inPositions[s.key] = handwritten[s.key] ?? builtInPositionText(n, s.key);
  return {
    n,
    slug: a.slug,
    title: a.title,
    roman: roman(n),
    matrix_number: n,
    short: a.short,
    keywords: a.keywords,
    meaning: a.meaning.join("\n\n"),
    in_positions: inPositions,
    plus: a.plus,
    minus: a.minus,
    combinations,
    seo: {
      // точная форма запроса: «N в матрице судьбы» — 505k показов на категорию, и именно эта
      // фраза, а не «N аркан», стоит в топе по всем 22 числам
      title: `${n} в матрице судьбы — значение аркана ${a.title}`,
      description: `${a.title} (${n} аркан): ${a.short}. Значение в характере, деньгах, отношениях и предназначении, плюсы и минусы, все 21 сочетание.`,
      queries: [`${n} аркан`, `${a.title.toLowerCase()} матрица судьбы`, ...a.keywords.slice(0, 3)],
    },
  };
}

