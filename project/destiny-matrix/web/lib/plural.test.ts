import { describe, expect, it } from "vitest";

import { counted, plural } from "./plural";

describe("согласование с числом", () => {
  it.each([
    [1, "платёж"], [2, "платежа"], [4, "платежа"], [5, "платежей"], [10, "платежей"],
    [11, "платежей"], [12, "платежей"], [14, "платежей"], [21, "платёж"], [22, "платежа"],
    [25, "платежей"], [101, "платёж"], [111, "платежей"], [592, "платежа"], [0, "платежей"],
  ])("%i → %s", (n, form) => {
    expect(plural(n, "платёж", "платежа", "платежей")).toBe(form);
  });

  it("печатает число вместе со словом", () => {
    expect(counted(1, "дата", "даты", "дат")).toBe("1 дата");
    expect(counted(22, "аркан", "аркана", "арканов")).toBe("22 аркана");
    expect(counted(231, "сочетание", "сочетания", "сочетаний")).toBe("231 сочетание");
    expect(counted(5544, "карта", "карты", "карт")).toBe("5544 карты");
  });
});
