export const dynamic = "force-dynamic";

export async function generateMetadata(): Promise<Metadata> {
  const prices = (await getTariffs()).map((t) => `${money(t.price)} ₽`).join(" / ");
  return pageMeta({
    title: "Публичная оферта",
    description:
      `Условия оказания услуг: состав разборов, цены ${prices}, порядок оплаты, ` +
      "ответственность сторон и порядок возврата.",
    path: "/oferta",
  });
}

/** Что именно оплачено — из scope тарифа: список возможностей отдельно от прав вести нельзя. */
function included(t: Tariff): string {
  const parts = [
    "все 20 разделов разбора",
    t.scope.includes("all") ? "любое число дат рождения" : "одна дата рождения",
  ];
  if (t.scope.includes("matrix")) parts.push("хранение матриц в личном кабинете");
  parts.push(t.period_days === null
    ? "доступ бессрочный"
    : `доступ ${periodLabel(t)}, по его окончании разборы закрываются`);
  return parts.join("; ");
}

