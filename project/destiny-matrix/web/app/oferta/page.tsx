export const dynamic = "force-dynamic";

export async function generateMetadata(): Promise<Metadata> {
  const list = (await getTariffs()).map((t) => `${money(t.price)} ₽`).join(" / ");
  const prices = list || "по действующему прайсу";
  return pageMeta({
    title: "Публичная оферта",
    description:
      `Условия выполнения работ: объём работ, цены ${prices}, порядок оплаты, ` +
      "передача результата, ответственность сторон и возврат.",
    path: "/oferta",
  });
}

/** Что входит в результат работ — из scope тарифа: состав отдельно от прав вести нельзя. */
function included(t: Tariff): string {
  const parts = [
    "все 20 разделов страницы",
    t.scope.includes("all") ? "любое число заданий" : "одно задание (одна дата рождения)",
  ];
  if (t.scope.includes("matrix")) parts.push("хранение заданий в личном кабинете");
  parts.push(t.period_days === null
    ? "экземпляр результата остаётся у заказчика бессрочно"
    : `доступ к результату ${periodLabel(t)}, по его окончании страница закрывается`);
  return parts.join("; ");
}

